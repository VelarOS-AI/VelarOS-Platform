#!/usr/bin/env node
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const repositoryRoot = join(dirname(fileURLToPath(import.meta.url)), '../../..')
const sourceDirectory = join(
  repositoryRoot,
  'packages/conversation-ui/src/html-preview'
)
const designCss = readFileSync(
  join(sourceDirectory, 'htmlPreviewSandboxDesign.css'),
  'utf8'
)
const svgFitCss = readFileSync(
  join(sourceDirectory, 'htmlPreviewSvgFitSandbox.css'),
  'utf8'
)
const output = `// Generated by scripts/build/generate-html-preview-css-module.mjs.
// Do not edit directly; edit the source CSS files instead.
export const HTML_PREVIEW_SANDBOX_DESIGN_CSS = ${JSON.stringify(designCss)}
export const HTML_PREVIEW_SANDBOX_SVG_FIT_CSS = ${JSON.stringify(svgFitCss)}
`

writeFileSync(
  join(sourceDirectory, 'htmlPreviewDesignCss.generated.ts'),
  output
)
