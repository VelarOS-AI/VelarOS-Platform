export type ConversationMessageTree = Readonly<{
  [key: string]: string | ConversationMessageTree
}>

type JoinMessageKey<Prefix extends string, Key extends string> = Prefix extends ''
  ? Key
  : `${Prefix}.${Key}`

type LeafMessageKeys<T, Prefix extends string = ''> = {
  [Key in keyof T & string]: T[Key] extends string
    ? JoinMessageKey<Prefix, Key>
    : T[Key] extends Readonly<Record<string, unknown>>
      ? LeafMessageKeys<T[Key], JoinMessageKey<Prefix, Key>>
      : never
}[keyof T & string]

export type CanonicalConversationMessageKey = LeafMessageKeys<
  typeof conversationZhCNMessages
>

/** Host-provided tool catalogs are open by design; every other conversation key is closed. */
export type DynamicConversationMessageKey =
  `tools.${'categoryDescriptions' | 'categoryLabels' | 'permissionNames' | 'toolDescriptions'}.${string}`

export type MergedConversationMessages<Base, Overrides> = {
  readonly [Key in keyof Base | keyof Overrides]: Key extends keyof Overrides
    ? Key extends keyof Base
      ? Base[Key] extends ConversationMessageTree
        ? Overrides[Key] extends ConversationMessageTree
          ? MergedConversationMessages<Base[Key], Overrides[Key]>
          : Overrides[Key]
        : Overrides[Key]
      : Overrides[Key]
    : Key extends keyof Base
      ? Base[Key]
      : never
}

/**
 * Recursively layers host-owned wording and product-only namespaces over the shared catalog.
 * Neither input is mutated, so both products can keep their own immutable catalog exports.
 */
export function mergeConversationMessages<
  const Base extends ConversationMessageTree,
  const Overrides extends ConversationMessageTree,
>(base: Base, overrides: Overrides): MergedConversationMessages<Base, Overrides> {
  const merged: Record<string, string | ConversationMessageTree> = { ...base }

  for (const [key, overrideValue] of Object.entries(overrides)) {
    const baseValue = base[key]
    merged[key] =
      !isString(baseValue) &&
      !isString(overrideValue) &&
      isPresent(baseValue)
        ? mergeConversationMessages(baseValue, overrideValue)
        : overrideValue
  }

  return merged as MergedConversationMessages<Base, Overrides>
}

function collectConversationMessageKeys(
  catalog: ConversationMessageTree,
  prefix = '',
): CanonicalConversationMessageKey[] {
  const keys: CanonicalConversationMessageKey[] = []

  for (const [key, value] of Object.entries(catalog)) {
    const path = prefix.length > 0 ? `${prefix}.${key}` : key
    if (isString(value)) {
      keys.push(path as CanonicalConversationMessageKey)
      continue
    }
    keys.push(...collectConversationMessageKeys(value, path))
  }

  return keys
}

