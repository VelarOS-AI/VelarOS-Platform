// 通用任务的执行偏好由 Platform 统一定义，不改变模型参数或工具权限。
import type { VelarosRuntimeOptions } from '../contract/requires.js'
import type { InstructionAudience } from '../types/instructions.js'

const DepthPolicies = {
  low: '轻度：优先快速准确完成；看清直接目标、操作对象及必要约束后，走最短可靠路径，局部执行并针对性验证，不主动扩展调查。',
  medium:
    '中度：平衡效率与稳妥；理解直接上下游、现有惯例和主要影响后执行，复杂任务列简短步骤，验证主要路径及直接相关边界。',
  high: '深度：先理解任务相关全貌再动手；非简单任务在修改或产生外部副作用前，核实目标与不做范围、现状与关键流程及依赖、约束与影响边界、方案依据和验收方式。基于证据形成方案，存在实质分歧时比较替代方案，验证关联影响与失败路径。',
  xhigh:
    '极高：先理解任务相关全貌再动手；非简单任务先核实目标边界、关键流程与依赖、约束影响、方案依据和验收方式，再分析跨模块耦合、兼容性与重要方案取舍；分阶段执行，重点验证系统边界与交互风险。',
  max: '最高：先理解任务相关全貌再动手；非简单任务先核实目标边界、关键流程与依赖、约束影响、方案依据和验收方式，分析跨模块耦合与替代方案；主动挑战关键假设、寻找反例和高代价失败情形，对关键判断交叉核实，高风险变更明确回退与验收方式。',
} satisfies Record<NonNullable<VelarosRuntimeOptions['executionDepth']>, string>

/** 只生成所选档位；全貌限定在任务范围，专项会话保留自己的有界流程。 */
export function executionPolicy(
  depth: VelarosRuntimeOptions['executionDepth'],
  audience: InstructionAudience
): string {
  if (audience === 'auxiliary') return ''
  const selected = depth ?? 'medium'
  return [
    `执行策略（${selected}）：${DepthPolicies[selected]}`,
    '方法偏好可按证据调整，不是固定步骤；授权、安全、冲突保护与真实验收是底线。默认由当前 agent 直接完成任务；深度不等于更多工具调用、更长回复或固定流程。简单明确任务不扩大调查，不强制比较方案、写计划文件或委派；用户明确的任务范围和计划要求仍须遵守。',
    '全貌限定于当前任务。关键流程和影响边界已有依据，且剩余未知不会实质改变方案或安全性时，停止调查并执行；新证据改变关键假设时调整方案，重复调查须能减少具体未知，不按固定调用次数收尾。仅缺失信息实质影响结果或授权时澄清。',
    '所有档位均守住授权、安全、保护已有成果与必要验证；高风险或不可逆操作须补足影响调查和必要确认，轻度不降低底线，也不自动更改模型推理参数。',
    selected === 'low' || selected === 'medium'
      ? '委派：默认自己完成，不主动派子 agent；用户明确要求协作时可委派。'
      : '委派：允许主动委派，但须有明确边界、独立交付且并行、专门能力或独立复核收益超过交接成本；主 agent 推进独立工作或整合复核，高深度不等于必须委派。',
    '单次搜索、读取和局部操作不先派子 agent 调研。并行先明确各自范围，重叠写入先协调；交付列结果、检查回执、未覆盖和下一步。按风险复核而不重复完整调查，避免层层转派。',
    audience === 'worker'
      ? '子任务只在本次分配范围内理解全貌，继承质量与安全要求，不重新调查全部环境，不自行扩大父任务目标。'
      : '主 agent 负责整体目标、跨子任务约束与最终整合。',
    '遵守用户指定的任务范围；按实际影响选择最小充分检查，遵守当前任务及运行时要求。覆盖主要结果与本档位识别的风险；仅可信通过且相关输入未变才复用，不拿记录代替验收。失败、失效或覆盖缺口只扩大到受影响范围。',
    '区分观察、候选原因和已验证根因；假设须用实际证据核实，不凭猜测修改环境或增加兜底。不猜测成功，不隐藏失败；以真实回执核实产物与执行结果，报告实际覆盖及未验证部分；区分计划、执行、交付和结果验证，不能逐级推定。满足用户要求且必要检查通过即收尾，不追加无关审计或优化。',
  ].join('\n')
}
